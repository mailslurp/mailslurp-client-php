     */
    public function setIncludeMetaDataColumns($include_meta_data_columns)
    {

        if (is_null($include_meta_data_columns)) {
            array_push($this->openAPINullablesSetToNull, 'include_meta_data_columns');
        } else {
            $nullablesSetToNull = $this->getOpenAPINullablesSetToNull();
            $index = array_search('include_meta_data_columns', $nullablesSetToNull);
            if ($index !== FALSE) {
                unset($nullablesSetToNull[$index]);
                $this->setOpenAPINullablesSetToNull($nullablesSetToNull);
            }
        }

        $this->container['include_meta_data_columns'] = $include_meta_data_columns;

        return $this;
    }
